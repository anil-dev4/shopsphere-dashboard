export type LocaleContextValue = { language: Language; setLanguage: (language: Language) => void; t: (text: string) => string }
export const LocaleContext = createContext<LocaleContextValue | null>(null)
export const translate = (language: Language, text: string) => language === 'en' ? text : translations[text]?.[language] ?? text

export function useLocale() {
  const locale = useContext(LocaleContext)
  if (!locale) throw new Error('useLocale must be used inside LocaleProvider')
  return locale
}
